import { memo } from 'react';
import ReactMarkdown, { type Options } from 'react-markdown';
import remarkGfm from 'remark-gfm';
import remarkMath from 'remark-math';
import rehypeSanitize from 'rehype-sanitize';
import rehypeKatex from 'rehype-katex';
import rehypeHighlight from 'rehype-highlight';
import 'katex/dist/katex.min.css';
import 'highlight.js/styles/github-dark.css';

const remarkPlugins: Options['remarkPlugins'] = [remarkGfm, remarkMath];

// Order matters: sanitize FIRST (strips scripts, event handlers, javascript: URLs), then let the
// trusted renderers add their markup. KaTeX/highlight output is generated by us, not by authors.
const rehypePlugins: Options['rehypePlugins'] = [
  rehypeSanitize,
  rehypeKatex,
  [rehypeHighlight, { detect: false, ignoreMissing: true }],
];

const components: Options['components'] = {
  a: ({ href, children }) => {
    const external = !!href && /^https?:\/\//i.test(href);
    return (
      <a href={href} {...(external ? { target: '_blank', rel: 'noopener noreferrer' } : {})}>
        {children}
      </a>
    );
  },
};

/** Renders untrusted markdown safely. There is no dangerouslySetInnerHTML anywhere in the app. */
function Markdown({ source }: { source: string }) {
  return (
    <div className="wiki-content">
      <ReactMarkdown remarkPlugins={remarkPlugins} rehypePlugins={rehypePlugins} components={components}>
        {source}
      </ReactMarkdown>
    </div>
  );
}
export default memo(Markdown);
